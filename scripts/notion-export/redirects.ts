// Emit `static/_redirects` (Cloudflare Pages format) per tree-publish-plan §8.
//
// Three alias classes per locale, per page:
//   1. Bare-ID alias        /<locale>/<pageId>           → canonical
//   2. Prior-slug alias     /<locale>/<old-slug>-<pageId> → canonical
//   3. Move alias           (subset of 2 — automatically emitted when an
//                            ancestor's slug change cascades into a page's
//                            current slug; the prior-slug history catches it)
//
// The current slug is computed fresh each run; the history file accumulates
// over time so old URLs keep redirecting indefinitely.
//
// Status code: 302 (temporary) during dev — browsers and CDNs don't cache
// these, so mistakes can be undone by a redeploy. Flip to 301 (permanent)
// for production once URL space is stable.
//
// Sprint D ships EN-only. The es/pt branches are wired but the history
// stays empty until Phase 4.5 wires Crowdin.

import { writeFile } from "node:fs/promises";
import { computeSlug } from "./compute-slug.ts";
import type { Manifest } from "./manifest.ts";
import {
  appendIfNew,
  emptyHistory,
  LOCALES,
  priorPrefixes,
  type RedirectHistory,
  type LocaleCode,
  slugPrefix,
} from "./redirect-history.ts";

const DOCS_BASE = "/docs";

/** Locale → URL prefix served by Docusaurus. EN is at site root (`""`), others under `/<locale>`. */
function localePrefix(locale: LocaleCode): string {
  return locale === "en" ? "" : `/${locale}`;
}

/**
 * Compute the EN slug for each page using the manifest's EN titles.
 * Returns `pageId → canonical slug` (with leading `/` and trailing `-<pageId>`).
 */
function computeEnSlugs(manifest: Manifest): Map<string, string> {
  const titles = new Map<string, string>();
  for (const [id, entry] of Object.entries(manifest.pages)) {
    titles.set(id, entry.title);
  }
  const slugs = new Map<string, string>();
  for (const id of Object.keys(manifest.pages)) {
    slugs.set(id, computeSlug({ pageId: id, manifest, titlesByPageId: titles }));
  }
  return slugs;
}

type Redirect = { from: string; to: string; status: 302 };

/**
 * Build the redirect set from manifest + history. Mutates `history` by
 * appending new prefixes when slugs change; the caller is responsible for
 * persisting it.
 */
export function buildRedirects(
  manifest: Manifest,
  history: RedirectHistory,
): Redirect[] {
  const enSlugs = computeEnSlugs(manifest);
  const redirects: Redirect[] = [];

  for (const [pageId, entry] of Object.entries(manifest.pages)) {
    if (entry.isRoot) continue;

    for (const locale of LOCALES) {
      // For Sprint D, only EN slugs are computed. Translation locales reuse
      // the EN slug (matches what Docusaurus serves at `/<locale>/...`).
      const enSlug = enSlugs.get(pageId);
      if (!enSlug) continue;
      const canonical = `${DOCS_BASE}${enSlug}`;
      const canonicalUrl = `${localePrefix(locale)}${canonical}`;

      // (1) Bare-ID alias: /docs/<pageId> → canonical
      const bareIdUrl = `${localePrefix(locale)}${DOCS_BASE}/${pageId}`;
      if (bareIdUrl !== canonicalUrl) {
        redirects.push({ from: bareIdUrl, to: canonicalUrl, status: 302 });
      }

      // Track current prefix in history; emit aliases for prior prefixes.
      const currentPrefix = slugPrefix(enSlug, pageId);
      appendIfNew(history, pageId, locale, currentPrefix);

      for (const prior of priorPrefixes(history, pageId, locale)) {
        const priorUrl = `${localePrefix(locale)}${DOCS_BASE}/${prior}-${pageId}`;
        if (priorUrl === canonicalUrl) continue;
        redirects.push({ from: priorUrl, to: canonicalUrl, status: 302 });
      }
    }
  }

  return redirects;
}

/** Serialise to Cloudflare Pages `_redirects` file format. */
export function formatRedirects(redirects: Redirect[]): string {
  const lines = [
    "# Generated by scripts/notion-export. Do not edit by hand.",
    "# Bare-ID + prior-slug aliases per tree-publish-plan §8.",
    "",
  ];
  for (const r of redirects) {
    lines.push(`${r.from} ${r.to} ${r.status}`);
  }
  return lines.join("\n") + "\n";
}

export async function writeRedirectsFile(
  redirects: Redirect[],
  path: string,
): Promise<void> {
  await writeFile(path, formatRedirects(redirects), "utf8");
}
